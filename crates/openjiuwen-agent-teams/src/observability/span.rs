//! Span model of the team runtime: trace/span identity, the span tree and the attribute vocabulary.
//!
//! Python parity source: `openjiuwen/agent_teams/observability/span_context.py` (span identity
//! helpers) and the `span_attributes` constants used by `monitor_handler.py` and `rail.py`. This
//! module keeps only the pure data: no tracer, no exporter, no global registry — a [`TeamSpan`] is
//! an inert value the runtime hands to
//! [`ObservabilityHooks`](crate::observability::hooks::ObservabilityHooks) and, when the `otel`
//! feature lands, to the in-memory sink.
//!
//! # Identity
//!
//! A trace is identified by a random 32-character lowercase hex string and a span by a random
//! 16-character lowercase hex string, both generated from `uuid` v4. Generated ids therefore never
//! collide with the OTLP textual format; [`SpanContext::new`] does not validate caller-supplied
//! ids — they are trusted, which keeps replaying a recorded trace from another process possible.
//!
//! # The span tree
//!
//! The runtime builds a small tree per team run:
//!
//! ```text
//! team.{team_name}                 <- TeamSpan::root_for, one trace per run
//! ├── member.{member_name}         <- one per spawned member
//! │   └── round.{member}.{round}   <- one per member round
//! └── task.{task_id}               <- one per task-board entry
//! ```
//!
//! # Attribute inheritance
//!
//! Attribute propagation is *creation-time inheritance*: [`TeamSpan::child`] copies the parent's
//! attribute map into the child when the child is created. There is no global parent chain and no
//! lazy walk — a later [`TeamSpan::with_attribute`] on the child overrides the inherited key
//! locally and never mutates the parent. That keeps spans `Send`, cloneable and cheap to hand to a
//! hook running on a different task.
//!
//! Everything here is infallible: no function returns `Result`, because generating an id and
//! copying a map cannot fail.

use std::collections::BTreeMap;
use std::time::{SystemTime, UNIX_EPOCH};

use serde::{Deserialize, Serialize};
use serde_json::Value;
use uuid::Uuid;

/// Attribute key holding the team's display name.
pub const AT_TEAM_NAME: &str = "team.name";
/// Attribute key holding the team identity.
pub const AT_TEAM_ID: &str = "team.id";
/// Attribute key holding a member name.
pub const AT_MEMBER_NAME: &str = "member.name";
/// Attribute key holding a member role wire string.
pub const AT_MEMBER_ROLE: &str = "member.role";
/// Attribute key holding a task-board task id.
pub const AT_TASK_ID: &str = "task.id";
/// Attribute key holding the team session id (`gen_ai` semantic convention).
pub const GEN_AI_CONVERSATION_ID: &str = "gen_ai.conversation_id";
/// Attribute key marking a span as belonging to the team agent mode (`"team"`).
pub const OJ_AGENT_MODE: &str = "oj.agent.mode";

/// Identity of a span: the trace it belongs to and its own id.
///
/// Both ids are opaque strings here; see the module docs for their format.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize, Default)]
#[serde(default)]
pub struct SpanContext {
    /// Trace identity shared by every span of one team run (32 lowercase hex characters).
    pub trace_id: String,
    /// Span identity (16 lowercase hex characters when generated by this module).
    pub span_id: String,
}

impl SpanContext {
    /// Builds a context from caller-supplied ids.
    ///
    /// The ids are trusted as given: they are not validated, normalised or regenerated, so a trace
    /// recorded elsewhere can be replayed verbatim.
    #[must_use]
    pub fn new(trace_id: impl Into<String>, span_id: impl Into<String>) -> Self {
        Self {
            trace_id: trace_id.into(),
            span_id: span_id.into(),
        }
    }

    /// Returns a child context: same trace, fresh span id.
    #[must_use]
    pub fn child(&self) -> Self {
        Self::new(self.trace_id.clone(), new_span_id())
    }
}

/// One span of the in-process team trace.
///
/// A span is plain data: a name, its [`SpanContext`], an optional parent context, the attribute map
/// inherited at creation time, and the wall-clock start in milliseconds since the Unix epoch.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
#[serde(default)]
pub struct TeamSpan {
    /// Span name (`team.{name}`, `member.{name}`, `round.{member}.{round}`, `task.{id}`).
    pub name: String,
    /// This span's identity.
    pub context: SpanContext,
    /// The parent span's identity, absent for a root span.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub parent: Option<SpanContext>,
    /// Attributes in effect for this span, inherited at creation time.
    pub attributes: BTreeMap<String, Value>,
    /// Start time in milliseconds since the Unix epoch.
    pub started_at: u64,
}

impl TeamSpan {
    /// Builds a root span with a fresh trace and span id.
    ///
    /// The name is also recorded as [`AT_TEAM_NAME`].
    #[must_use]
    pub fn root(name: impl Into<String>) -> Self {
        let name = name.into();
        let mut attributes = BTreeMap::new();
        attributes.insert(AT_TEAM_NAME.to_owned(), Value::String(name.clone()));
        Self {
            name,
            context: SpanContext::new(new_trace_id(), new_span_id()),
            parent: None,
            attributes,
            started_at: now_ms(),
        }
    }

    /// Builds the root span of a team run, named `team.{team_name}`.
    ///
    /// Python parity: the root carries [`AT_TEAM_NAME`], [`AT_TEAM_ID`] and
    /// [`OJ_AGENT_MODE`] = `"team"`.
    #[must_use]
    pub fn root_for(team_name: impl Into<String>) -> Self {
        let team_name = team_name.into();
        let mut attributes = BTreeMap::new();
        attributes.insert(AT_TEAM_NAME.to_owned(), Value::String(team_name.clone()));
        attributes.insert(OJ_AGENT_MODE.to_owned(), Value::String("team".to_owned()));
        attributes.insert(AT_TEAM_ID.to_owned(), Value::String(team_name.clone()));
        Self {
            name: format!("team.{team_name}"),
            context: SpanContext::new(new_trace_id(), new_span_id()),
            parent: None,
            attributes,
            started_at: now_ms(),
        }
    }

    /// Returns a child span by *creation-time inheritance*.
    ///
    /// The child copies this span's attribute map at the moment it is created, gets a fresh span id
    /// in the same trace, records this span's context as its parent, and takes a fresh start time.
    /// Nothing is linked back to the parent afterwards: a
    /// [`with_attribute`](Self::with_attribute) call on the child overrides the inherited key only
    /// on the child, and this span's map is left untouched.
    #[must_use]
    pub fn child(&self, name: impl Into<String>) -> Self {
        Self {
            name: name.into(),
            context: self.context.child(),
            parent: Some(self.context.clone()),
            attributes: self.attributes.clone(),
            started_at: now_ms(),
        }
    }

    /// Returns this span with `key` set to `value`, replacing an inherited or earlier value.
    #[must_use]
    pub fn with_attribute(mut self, key: impl Into<String>, value: Value) -> Self {
        self.attributes.insert(key.into(), value);
        self
    }

    /// Returns the value of `key`, or `None` when the span does not carry it.
    #[must_use]
    pub fn attribute(&self, key: &str) -> Option<&Value> {
        self.attributes.get(key)
    }

    /// Returns the trace id this span belongs to.
    #[must_use]
    pub fn trace_id(&self) -> &str {
        &self.context.trace_id
    }

    /// Returns this span's own id.
    #[must_use]
    pub fn span_id(&self) -> &str {
        &self.context.span_id
    }
}

/// Generates a fresh 32-character lowercase hex trace id.
fn new_trace_id() -> String {
    Uuid::new_v4().simple().to_string()
}

/// Generates a fresh 16-character lowercase hex span id.
fn new_span_id() -> String {
    let bytes = Uuid::new_v4().into_bytes();
    let mut value: u64 = 0;
    for byte in bytes.iter().take(8) {
        value = (value << 8) | u64::from(*byte);
    }
    format!("{value:016x}")
}

/// Current wall-clock time in milliseconds since the Unix epoch, saturating at [`u64::MAX`].
fn now_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |dur| u64::try_from(dur.as_millis()).unwrap_or(u64::MAX))
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used)]
mod tests {
    use super::*;

    fn is_lower_hex(value: &str) -> bool {
        value
            .chars()
            .all(|c| c.is_ascii_hexdigit() && !c.is_ascii_uppercase())
    }

    fn json(value: &str) -> Value {
        Value::String(value.to_owned())
    }

    #[test]
    fn root_generates_32_and_16_lowercase_hex_ids() {
        let span = TeamSpan::root("demo");
        assert_eq!(span.trace_id().len(), 32);
        assert_eq!(span.span_id().len(), 16);
        assert!(is_lower_hex(span.trace_id()));
        assert!(is_lower_hex(span.span_id()));
        assert!(span.parent.is_none());
        assert!(span.started_at > 0);
    }

    #[test]
    fn root_for_sets_python_parity_attributes() {
        let span = TeamSpan::root_for("alpha");
        assert_eq!(span.name, "team.alpha");
        assert_eq!(span.attribute(AT_TEAM_NAME), Some(&json("alpha")));
        assert_eq!(span.attribute(AT_TEAM_ID), Some(&json("alpha")));
        assert_eq!(span.attribute(OJ_AGENT_MODE), Some(&json("team")));
    }

    #[test]
    fn root_name_is_the_team_name_attribute() {
        let span = TeamSpan::root("custom-root");
        assert_eq!(span.name, "custom-root");
        assert_eq!(span.attribute(AT_TEAM_NAME), Some(&json("custom-root")));
    }

    #[test]
    fn child_keeps_trace_and_gets_fresh_span_id() {
        let parent = TeamSpan::root_for("alpha");
        let child = parent.child("member.dev");
        assert_eq!(child.trace_id(), parent.trace_id());
        assert_ne!(child.span_id(), parent.span_id());
        assert_eq!(child.span_id().len(), 16);
        assert_eq!(child.parent, Some(parent.context.clone()));
        assert_eq!(child.name, "member.dev");
    }

    #[test]
    fn child_inherits_attributes_at_creation_time() {
        let parent = TeamSpan::root_for("alpha");
        let child = parent.child("member.dev");
        assert_eq!(child.attributes, parent.attributes);
        assert_eq!(child.attribute(AT_TEAM_NAME), Some(&json("alpha")));
    }

    #[test]
    fn child_override_does_not_touch_parent_attributes() {
        let parent = TeamSpan::root_for("alpha");
        let child = parent
            .child("member.dev")
            .with_attribute(AT_MEMBER_NAME, json("dev"));
        assert_eq!(child.attribute(AT_MEMBER_NAME), Some(&json("dev")));
        assert!(parent.attribute(AT_MEMBER_NAME).is_none());
        assert_eq!(child.attribute(AT_TEAM_NAME), Some(&json("alpha")));
    }

    #[test]
    fn with_attribute_replaces_and_absent_key_is_none() {
        let span = TeamSpan::root("demo");
        assert!(span.attribute("nope").is_none());
        let span = span
            .with_attribute(AT_TASK_ID, json("t-1"))
            .with_attribute(AT_TASK_ID, json("t-2"));
        assert_eq!(span.attribute(AT_TASK_ID), Some(&json("t-2")));
    }

    #[test]
    fn span_and_context_round_trip_through_json() {
        let span = TeamSpan::root_for("alpha").child("round.dev.2");
        let text = serde_json::to_string(&span).unwrap();
        let back: TeamSpan = serde_json::from_str(&text).unwrap();
        assert_eq!(back, span);

        let context = SpanContext::new("trace", "span");
        let text = serde_json::to_string(&context).unwrap();
        let back: SpanContext = serde_json::from_str(&text).unwrap();
        assert_eq!(back, context);
    }

    #[test]
    fn span_tolerates_unknown_and_missing_fields() {
        let back: TeamSpan = serde_json::from_str(r#"{"name":"n","extra":1}"#).unwrap();
        assert_eq!(back.name, "n");
        assert_eq!(back.context, SpanContext::default());
        assert!(back.parent.is_none());
        assert!(back.attributes.is_empty());

        let span = TeamSpan::root("demo");
        let mut value = serde_json::to_value(&span).unwrap();
        assert!(
            value.get("parent").is_none(),
            "parent is skipped when absent"
        );
        value["started_at"] = json("ignored");
        assert!(serde_json::from_value::<TeamSpan>(value).is_err());
    }

    #[test]
    fn context_child_keeps_trace_and_regenerates_span() {
        let parent = SpanContext::new("abc", "def");
        let child = parent.child();
        assert_eq!(child.trace_id, "abc");
        assert_eq!(child.span_id.len(), 16);
        assert_ne!(child.span_id, parent.span_id);
    }
}
